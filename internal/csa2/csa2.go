func (s *streamState) stream8() [8]byte { var out [8]byte; for i:=0;i<8;i++ { var op uint8; for j:=0;j<4;j++ { s.step(false,0,0,j); d:=s.D^(s.D>>1); op=(op<<2)|((((d>>1)&2)|(d&1))&3) }; out[i]=op }; return out }

func (s *streamState) xor(data []byte) { for off:=0;off<len(data); { ks:=s.stream8(); n:=len(data)-off; if n>8 { n=8 }; for i:=0;i<n;i++ { data[off+i]^=ks[i] }; off+=n } }


func Encrypt(data []byte, cw [8]byte) error {
 if len(data)<8 { return fmt.Errorf("CSA2 payload must be at least 8 bytes") }
 kk:=computeKey(cw)
 n:=len(data)/8
 residue:=len(data)%8
 blocks:=make([][8]byte,n+1)
 for i:=n-1;i>=0;i-- {
  var b [8]byte
  for j:=0;j<8;j++ { b[j]=data[i*8+j]^blocks[i+1][j] }
  blocks[i]=blockEncrypt(&kk,b)
 }
 copy(data[:8],blocks[0][:])
 var st streamState
 st.init(cw,blocks[0])
 for i:=1;i<n;i++ {
  tmp:=make([]byte,8); copy(tmp,blocks[i][:]); st.xor(tmp); copy(data[i*8:],tmp)
 }
 if residue>0 {
  tmp:=make([]byte,residue); st.xor(tmp); copy(data[n*8:],tmp)
 }
 return nil
}

func Decrypt(data []byte, cw [8]byte) error {
 if len(data)<8 { return fmt.Errorf("CSA2 payload must be at least 8 bytes") }
 kk:=computeKey(cw)
 n:=len(data)/8
 residue:=len(data)%8
 var ib [8]byte
 copy(ib[:],data[:8])
 var st streamState
 st.init(cw,ib)
 for i:=0;i<n;i++ {
  block:=blockDecrypt(&kk,ib)
  var next [8]byte
  if i+1<n {
   copy(next[:],data[(i+1)*8:(i+2)*8])
   tmp:=next[:]; st.xor(tmp); copy(next[:],tmp)
  } else {
   for j:=range next { next[j]=0 }
  }
  for j:=0;j<8;j++ { data[i*8+j]=next[j]^block[j] }
  ib=next
 }
 if residue>0 {
  tmp:=data[n*8:]; st.xor(tmp)
 }
 return nil
}
